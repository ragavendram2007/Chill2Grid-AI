@st.cache_data
def get_facilities() -> List[Facility]:
    fac_csv = PROJECT_ROOT / "data" / "facilities.csv"
    return load_facilities_from_csv(fac_csv)


def get_tier_color(tier: str) -> str:
    if tier == "CRITICAL":
        return "#EF4444"
    if tier == "HIGH":
        return "#F59E0B"
    return "#10B981"


@st.cache_data
def compute_live_fleet_telemetry(outside_temp: float, load_frac: float, door_rate: float) -> List[Dict[str, Any]]:
    facilities = get_facilities()
    guardian = get_default_guardian()
    # Ensure clean evaluation state
    guardian.debt_ledger.history.clear()

    tier_map = {
        "FAC-VAX-03": "CRITICAL",
        "FAC-FZN-01": "HIGH",
        "FAC-ICE-02": "HIGH",
        "FAC-PRD-04": "STANDARD",
        "FAC-SEA-05": "STANDARD",
        "FAC-MLK-06": "STANDARD",
    }

    card_data = []
    for fac in facilities:
        tier = tier_map.get(fac.id, "STANDARD")
        # Current temp calibrated near setpoint with passive heat bias
        current_temp = fac.min_temp_c + 0.1 + 0.3 * (outside_temp - 25.0) / 15.0
        headroom = fac.max_safe_temp_c - current_temp

        snap = FleetSnapshot(
            facility_id=fac.id,
            temp_c=current_temp,
            outside_temp_c=outside_temp,
            humidity_pct=50.0,
            product_load_fraction=load_frac,
            door_openings_per_hour=door_rate,
            compressor_on=True,
            sensor_ok=True,
            timestamp_min=1080.0,
            minutes_in_current_state=45.0,
        )

        # 30-min request to evaluate guardian live
        req = CurtailmentAction(fac.id, start_min=1080, duration_min=30)
        verdict = guardian.evaluate_request(req, snap)

        # Forecast band calculation (60 min horizon)
        time_mins = np.arange(0, 65, 5)
        k_rate = 0.05 * (outside_temp - current_temp) / 30.0
        t_nominal = current_temp + k_rate * time_mins
        t_upper = t_nominal + 0.35 * np.sqrt(time_mins / 10.0)
        t_lower = t_nominal - 0.25 * np.sqrt(time_mins / 10.0)

        card_data.append({
            "id": fac.id,
            "name": fac.name or fac.id,
            "product": fac.product_type,
            "tier": tier,
            "color": get_tier_color(tier),
            "rated_kw": fac.rated_power_kw,
            "setpoint_c": fac.min_temp_c,
            "max_safe_c": fac.max_safe_temp_c,
            "current_temp": current_temp,
            "headroom": headroom,
            "verdict_decision": verdict.decision,
            "approved_min": verdict.approved_duration_min,
            "binding_constraint": verdict.binding_constraint,
            "plain_English": verdict.plain_English,
            "time_mins": time_mins.tolist(),
            "t_nominal": t_nominal.tolist(),
            "t_upper": t_upper.tolist(),
            "t_lower": t_lower.tolist(),
        })

    return card_data


