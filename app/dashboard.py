@st.cache_data
def load_readiness_status() -> Dict[str, Any]:
    readiness_path = PROJECT_ROOT / "outputs" / "part4" / "readiness.json"
    if not readiness_path.is_file():
        return {"status": "NOT READY", "all_checks_passed": False, "tests_passed": 0}
    try:
        with open(readiness_path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {"status": "NOT READY", "all_checks_passed": False, "tests_passed": 0}


